#!/usr/bin/env python3
"""Generate the LiteCowork desktop/local V1 release qualification matrix.

The matrix is *generated by probing this environment*. A cell is only reported
as PASSED when the probe actually ran on this host and observed success here.
Every other cell is NOT RUN or BLOCKED together with the reason and the exact
command a qualified operator has to run.

The script never invents a PASSED cell, never claims an operating system it did
not run on, and never claims an agent version it did not observe.

Usage:
    .venv/bin/python scripts/v1_platform_matrix.py \
        --out implementation/QUALIFICATION-MATRIX.md \
        --evidence-out /tmp/litecowork-release-evidence

Exit code is 0 when the probes that ran all passed. A blocked probe is a
truthful outcome, not a script failure.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent

# The agent roster the repository knows about. Each entry is the executable the
# harness is expected to provide; the script records the version it observes.
AGENT_EXECUTABLES: dict[str, tuple[str, ...]] = {
    "cline": ("cline",),
    "codex": ("codex",),
    "opencode": ("opencode",),
    "claude-code": ("claude",),
    "copilot": ("copilot",),
    "droid": ("droid",),
    "gemini": ("gemini",),
    "goose": ("goose",),
    "qwen": ("qwen",),
}

# The exact browser executables the browser takeover surface can drive.
BROWSER_EXECUTABLES: dict[str, tuple[str, ...]] = {
    "google-chrome": ("google-chrome", "google-chrome-stable", "chrome"),
    "chromium": ("chromium", "chromium-browser"),
    "microsoft-edge": ("microsoft-edge", "msedge"),
    "firefox": ("firefox",),
}

# Capabilities the release matrix must carry, per the E13 mandatory gate list.
CAPABILITIES: tuple[str, ...] = (
    "native_conversation_send",
    "producer_scoped_planner_isolation",
    "workspace_root_revalidation",
    "coworker_private_learner",
    "browser_takeover",
    "terminal_pty",
    "effect_reconciliation",
    "independent_verification",
    "backup_restore",
    "packaging",
    "secret_scan",
)

# The operating systems the desktop product may be released for. Only the host
# the script runs on can be probed; the others stay BLOCKED with the reason.
SUPPORTED_PLATFORMS: tuple[tuple[str, str], ...] = (
    ("linux", "x86_64"),
    ("windows", "x86_64"),
    ("macos", "aarch64"),
)


@dataclass
class Cell:
    """One matrix cell with its truthful state and evidence."""

    state: str
    command: str
    observation: str
    reason: str = ""

    def as_dict(self) -> dict[str, Any]:
        return {
            "state": self.state,
            "command": self.command,
            "observation": self.observation,
            "reason": self.reason,
        }


@dataclass
class Evidence:
    host: dict[str, Any] = field(default_factory=dict)
    toolchains: dict[str, str] = field(default_factory=dict)
    agents: dict[str, dict[str, Any]] = field(default_factory=dict)
    browsers: dict[str, dict[str, Any]] = field(default_factory=dict)
    probes: dict[str, Cell] = field(default_factory=dict)
    generated_at: str = ""


def run(command: list[str], cwd: Path | None = None, timeout: int = 900) -> tuple[int, str]:
    """Runs a command and returns its exit code and combined output."""
    try:
        completed = subprocess.run(
            command,
            cwd=str(cwd) if cwd else None,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except FileNotFoundError:
        return 127, "command not found"
    except subprocess.TimeoutExpired:
        return 124, "command timed out"
    output = (completed.stdout or "") + (completed.stderr or "")
    return completed.returncode, output.strip()


def probe_host() -> dict[str, Any]:
    return {
        "system": platform.system(),
        "release": platform.release(),
        "machine": platform.machine(),
        "platform": platform.platform(),
        "python": platform.python_version(),
        "node": os.uname().nodename if hasattr(os, "uname") else "unknown",
    }


def probe_toolchains() -> dict[str, str]:
    toolchains: dict[str, str] = {}
    probes = {
        "rustc": ["rustc", "--version"],
        "cargo": ["cargo", "--version"],
        "node": ["node", "--version"],
        "pnpm": ["pnpm", "--version"],
        "python": ["python3", "--version"],
    }
    for name, command in probes.items():
        if shutil.which(command[0]) is None:
            toolchains[name] = "NOT INSTALLED"
            continue
        code, output = run(command, timeout=60)
        toolchains[name] = output if code == 0 else f"FAILED ({code})"
    return toolchains


def probe_agents() -> dict[str, dict[str, Any]]:
    agents: dict[str, dict[str, Any]] = {}
    for agent, executables in AGENT_EXECUTABLES.items():
        found: dict[str, Any] = {
            "executable": None,
            "version": None,
            "state": "NOT INSTALLED",
            "command": "",
            "observation": "",
        }
        for executable in executables:
            path = shutil.which(executable)
            if path is None:
                continue
            found["executable"] = executable
            command = [executable, "--version"]
            code, output = run(command, timeout=60)
            found["command"] = " ".join(command)
            if code == 0:
                found["version"] = output.splitlines()[0] if output else "unknown"
                found["state"] = "PRESENT"
                found["observation"] = output.splitlines()[0] if output else ""
            else:
                found["state"] = "PRESENT BUT UNREPORTED"
                found["observation"] = output[:200]
            break
        agents[agent] = found
    return agents


def probe_browsers() -> dict[str, dict[str, Any]]:
    browsers: dict[str, dict[str, Any]] = {}
    for browser, executables in BROWSER_EXECUTABLES.items():
        found: dict[str, Any] = {
            "executable": None,
            "version": None,
            "state": "NOT INSTALLED",
            "command": "",
            "observation": "",
        }
        for executable in executables:
            path = shutil.which(executable)
            if path is None:
                continue
            found["executable"] = executable
            command = [executable, "--version"]
            code, output = run(command, timeout=60)
            found["command"] = " ".join(command)
            if code == 0:
                found["version"] = output.splitlines()[0] if output else "unknown"
                found["state"] = "PRESENT"
                found["observation"] = output.splitlines()[0] if output else ""
            else:
                found["state"] = "PRESENT BUT UNREPORTED"
                found["observation"] = output[:200]
            break
        browsers[browser] = found
    return browsers


def probe_secret_service() -> Cell:
    """Probes whether a desktop Secret Service is reachable on this host."""
    command = [
        "dbus-send",
        "--session",
        "--dest=org.freedesktop.DBus",
        "--type=method_call",
        "--print-reply",
        "/org/freedesktop/DBus",
        "org.freedesktop.DBus.ListNames",
    ]
    if shutil.which("dbus-send") is None:
        return Cell(
            state="BLOCKED",
            command=" ".join(command),
            observation="dbus-send is not installed",
            reason="the OS credential store cannot be probed without a session bus",
        )
    code, output = run(command, timeout=60)
    if code != 0:
        return Cell(
            state="BLOCKED",
            command=" ".join(command),
            observation=output[:200],
            reason="no session bus is reachable",
        )
    if "org.freedesktop.secrets" in output:
        return Cell(
            state="PASSED",
            command=" ".join(command),
            observation="org.freedesktop.secrets is registered",
        )
    return Cell(
        state="BLOCKED",
        command=" ".join(command),
        observation="no org.freedesktop.secrets service is registered",
        reason="the OS credential store is unavailable on this host",
    )


def probe_backup_restore() -> Cell:
    command = [
        "cargo",
        "test",
        "--locked",
        "--offline",
        "--jobs",
        "2",
        "-p",
        "storage-sqlite",
        "backup::",
    ]
    code, output = run(command, cwd=REPOSITORY_ROOT, timeout=3600)
    if code == 0:
        return Cell(
            state="PASSED",
            command=" ".join(command),
            observation=tail(output),
        )
    return Cell(
        state="FAILED",
        command=" ".join(command),
        observation=tail(output),
        reason="the backup/restore storage suite did not pass on this host",
    )


def probe_packaging() -> Cell:
    command = [sys.executable, "scripts/v1_packaging_check.py"]
    code, output = run(command, cwd=REPOSITORY_ROOT, timeout=900)
    if code == 0:
        return Cell(
            state="PASSED",
            command=" ".join(command),
            observation=tail(output),
        )
    return Cell(
        state="FAILED",
        command=" ".join(command),
        observation=tail(output),
        reason="the packaging checks did not pass on this host",
    )


def probe_secret_scan() -> Cell:
    command = [sys.executable, "scripts/v1_secret_scan.py"]
    code, output = run(command, cwd=REPOSITORY_ROOT, timeout=900)
    if code == 0:
        return Cell(
            state="PASSED",
            command=" ".join(command),
            observation=tail(output),
        )
    return Cell(
        state="FAILED",
        command=" ".join(command),
        observation=tail(output),
        reason="the secret scan found material in the built artifacts",
    )


def tail(output: str, lines: int = 6) -> str:
    trimmed = output.strip().splitlines()
    return "\n".join(trimmed[-lines:]) if trimmed else ""


def build_evidence() -> Evidence:
    evidence = Evidence()
    evidence.generated_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    evidence.host = probe_host()
    evidence.toolchains = probe_toolchains()
    evidence.agents = probe_agents()
    evidence.browsers = probe_browsers()
    evidence.probes["os_credential_store"] = probe_secret_service()
    evidence.probes["backup_restore"] = probe_backup_restore()
    evidence.probes["packaging"] = probe_packaging()
    evidence.probes["secret_scan"] = probe_secret_scan()
    return evidence


def host_platform(evidence: Evidence) -> tuple[str, str]:
    """The (system, architecture) key of the probing host."""
    return evidence.host["system"].lower(), evidence.host["machine"]


def platform_cell(evidence: Evidence, capability: str) -> Cell:
    """Resolves one capability cell for the operating system of this host."""
    host = evidence.host
    if capability == "backup_restore":
        return evidence.probes["backup_restore"]
    if capability == "packaging":
        return evidence.probes["packaging"]
    if capability == "secret_scan":
        return evidence.probes["secret_scan"]
    credential = evidence.probes["os_credential_store"]
    if credential.state != "PASSED":
        return Cell(
            state="BLOCKED",
            command="see implementation/reviews/E13-S03.md",
            observation=credential.observation,
            reason=(
                "the OS credential store is unavailable on this host, so the daemon cannot "
                "reach a state where this capability can be exercised"
            ),
        )
    return Cell(
        state="NOT RUN",
        command=f"see implementation/reviews/E13-S03.md for the exact {capability} command",
        observation="not exercised by this generator",
        reason=(
            "this capability needs a qualified operator with the real provider and a real "
            f"{host['system']} desktop session"
        ),
    )


def render(evidence: Evidence) -> str:
    host = evidence.host
    lines: list[str] = []
    lines.append("# LiteCowork desktop/local V1 release qualification matrix")
    lines.append("")
    lines.append(
        "This file is generated. Do not edit it by hand: run the command below to regenerate it."
    )
    lines.append("")
    lines.append("```")
    lines.append(
        ".venv/bin/python scripts/v1_platform_matrix.py "
        "--out implementation/QUALIFICATION-MATRIX.md "
        "--evidence-out /tmp/litecowork-release-evidence"
    )
    lines.append("```")
    lines.append("")
    lines.append(f"- Generated at: `{evidence.generated_at}`")
    lines.append(
        f"- Probing host: `{host['system']} {host['release']} {host['machine']}` "
        f"(python {host['python']})"
    )
    lines.append(
        "- A cell is `PASSED` only when the probe actually ran on this host and observed "
        "success. Every other cell carries the reason it is not a pass."
    )
    lines.append("- `NOT RUN` means the probe exists but was not executed here.")
    lines.append("- `BLOCKED` means the environment cannot run the probe at all.")
    lines.append("")
    lines.append("## Toolchain observed on the probing host")
    lines.append("")
    lines.append("| Tool | Observed |")
    lines.append("|---|---|")
    for name, value in sorted(evidence.toolchains.items()):
        lines.append(f"| {name} | `{value}` |")
    lines.append("")

    lines.append("## Platform capability matrix")
    lines.append("")
    host_system, host_machine = host_platform(evidence)
    wsl = "wsl" in host["release"].lower() or "microsoft" in host["release"].lower()

    def column_label(system: str, arch: str) -> str:
        label = f"{system}/{arch}"
        if system == host_system and wsl:
            label += " (wsl2)"
        return label

    header = "| Capability | " + " | ".join(
        column_label(system, arch) for system, arch in SUPPORTED_PLATFORMS
    ) + " |"
    lines.append(header)
    lines.append("|---" * (len(SUPPORTED_PLATFORMS) + 1) + "|")
    for capability in CAPABILITIES:
        cells: list[str] = []
        for system, arch in SUPPORTED_PLATFORMS:
            if system == host_system:
                cells.append(platform_cell(evidence, capability).state)
            else:
                cells.append("BLOCKED")
        lines.append(f"| {capability} | " + " | ".join(cells) + " |")
    lines.append("")
    if "wsl" in host["release"].lower() or "microsoft" in host["release"].lower():
        lines.append(
            "> **Host note:** this probing host is a WSL2 environment, not a native Linux "
            "desktop kernel. Process isolation, file identity, PTY and browser takeover "
            "behaviour on WSL2 is not the behaviour on a native Linux desktop, so a cell "
            "probed here is not a native Linux desktop qualification."
        )
        lines.append("")
    lines.append("### Per-cell evidence for the probed host")
    lines.append("")
    for capability in CAPABILITIES:
        cell = platform_cell(evidence, capability)
        lines.append(f"#### {capability}")
        lines.append("")
        lines.append(f"- State: **{cell.state}**")
        lines.append(f"- Command: `{cell.command}`")
        if cell.observation:
            lines.append("- Observation:")
            lines.append("")
            lines.append("```")
            lines.append(cell.observation)
            lines.append("```")
        if cell.reason:
            lines.append(f"- Reason: {cell.reason}")
        lines.append("")

    lines.append("## Agent and harness matrix")
    lines.append("")
    lines.append(
        "An agent is only supported when its exact version passes the native harness "
        "conformance on the exact operating system. A detected version is an "
        "observation, not a qualification."
    )
    lines.append("")
    lines.append("| Agent | Executable | Observed version | State |")
    lines.append("|---|---|---|---|")
    for agent, facts in sorted(evidence.agents.items()):
        lines.append(
            f"| {agent} | `{facts['executable'] or '-'}` | "
            f"`{facts['version'] or '-'}` | {facts['state']} |"
        )
    lines.append("")

    lines.append("## Browser matrix")
    lines.append("")
    lines.append("| Browser | Executable | Observed version | State |")
    lines.append("|---|---|---|---|")
    for browser, facts in sorted(evidence.browsers.items()):
        lines.append(
            f"| {browser} | `{facts['executable'] or '-'}` | "
            f"`{facts['version'] or '-'}` | {facts['state']} |"
        )
    lines.append("")

    lines.append("## Cells that are not a pass")
    lines.append("")
    lines.append("| Capability | State | Reason |")
    lines.append("|---|---|---|")
    for capability in CAPABILITIES:
        cell = platform_cell(evidence, capability)
        if cell.state == "PASSED":
            continue
        lines.append(f"| {capability} | {cell.state} | {cell.reason or '-'} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default="implementation/QUALIFICATION-MATRIX.md",
        help="the markdown matrix the generator writes",
    )
    parser.add_argument(
        "--evidence-out",
        default="/tmp/litecowork-release-evidence",
        help="the directory the machine readable evidence is written to",
    )
    parser.add_argument(
        "--skip-slow-probes",
        action="store_true",
        help="skip the cargo test and packaging probes (the matrix then reports them as NOT RUN)",
    )
    arguments = parser.parse_args()

    evidence = build_evidence()
    if arguments.skip_slow_probes:
        for name in ("backup_restore", "packaging", "secret_scan"):
            evidence.probes[name] = Cell(
                state="NOT RUN",
                command="re-run without --skip-slow-probes",
                observation="skipped by request",
                reason="the probe was skipped by the caller",
            )

    output_path = Path(arguments.out)
    if not output_path.is_absolute():
        output_path = REPOSITORY_ROOT / output_path
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render(evidence), encoding="utf-8")

    evidence_directory = Path(arguments.evidence_out)
    evidence_directory.mkdir(parents=True, exist_ok=True)
    evidence_path = evidence_directory / "platform-matrix-evidence.json"
    evidence_path.write_text(
        json.dumps(
            {
                "generated_at": evidence.generated_at,
                "host": evidence.host,
                "toolchains": evidence.toolchains,
                "agents": evidence.agents,
                "browsers": evidence.browsers,
                "probes": {name: cell.as_dict() for name, cell in evidence.probes.items()},
            },
            indent=2,
            sort_keys=True,
        ),
        encoding="utf-8",
    )
    print(f"matrix: {output_path}")
    print(f"evidence: {evidence_path}")
    failures = [
        name for name, cell in evidence.probes.items() if cell.state == "FAILED"
    ]
    if failures:
        print(f"FAILED probes: {', '.join(sorted(failures))}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
