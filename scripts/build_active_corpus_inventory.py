#!/usr/bin/env python3
"""Build the active first-party Markdown corpus manifest.

The manifest excludes historical archives, derived reading digests, reference clones,
generated audit outputs and dependency/build/worktree directories. It records inventory
and hashes only; it does not certify semantic correctness or implementation status.
"""
from __future__ import annotations

import csv
import hashlib
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/audit"
MANIFEST = ROOT / "docs/COMPLETE-ACTIVE-CORPUS-INVENTORY.md"
CSV_PATH = OUTPUT / "active-corpus-manifest.csv"
SKIP = {
    ".git", "node_modules", "target", ".venv", ".pytest_cache",
    ".agent-worktrees", ".worktrees", ".zwork", ".superpowers",
    "archives", "archive", "repo_take", "reading", "staging_tar", "dist", "build",
    "coverage", ".next", ".cache", "vendor", "out", ".turbo", "audit",
}
EXCLUDED = {
    "docs/COMPLETE-ACTIVE-CORPUS-INVENTORY.md",
}

def collect():
    records = []
    for folder, dirs, names in os.walk(ROOT):
        dirs[:] = [name for name in dirs if name not in SKIP]
        for name in names:
            path = Path(folder) / name
            if path.suffix.lower() not in {".md", ".mdx"}:
                continue
            rel = path.relative_to(ROOT).as_posix()
            if rel in EXCLUDED:
                continue
            data = path.read_bytes()
            decoded = data.decode("utf-8-sig", errors="replace")
            records.append({
                "path": rel,
                "lines": len(decoded.splitlines()),
                "bytes": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
            })
    return sorted(records, key=lambda row: row["path"])

def emit(records):
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with CSV_PATH.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(
            stream,
            fieldnames=["path", "lines", "bytes", "sha256"],
            lineterminator="\n",
        )
        writer.writeheader()
        writer.writerows(records)

    by_area = {}
    for row in records:
        parts = row["path"].split("/")
        if parts[0] == "docs":
            area = "docs/"
        elif parts[0] == "specs":
            area = "specs/"
        elif parts[0] == ".specify":
            area = ".specify/"
        elif parts[0] in {"apps", "crates", "capabilities", "tests", "scripts"}:
            area = parts[0] + "/"
        else:
            area = "repository root"
        by_area.setdefault(area, []).append(row)

    total_lines = sum(row["lines"] for row in records)
    total_bytes = sum(row["bytes"] for row in records)
    lines = [
        "# Complete active documentation corpus inventory",
        "",
        "Generated by scripts/build_active_corpus_inventory.py. This manifest enumerates",
        "active first-party Markdown/MDX documents and code-package READMEs. It excludes",
        "historical archives, derived reading digests, external reference repositories,",
        "generated audit output, local worktrees, build artifacts and dependencies.",
        "",
        "This is an inventory, not proof that every sentence is correct, implemented,",
        "integrated or qualified. The authority chain is in docs/README.md. Current source",
        "evidence is in docs/IMPLEMENTATION-STATUS.md.",
        "",
        f"- Included files: {len(records)}",
        f"- Included lines: {total_lines}",
        f"- Included bytes: {total_bytes}",
        f"- Per-file SHA-256: docs/audit/active-corpus-manifest.csv",
        "- This manifest excludes itself to avoid a self-referential hash/count.",
        "- reading/ contains derived audit snapshots and is intentionally excluded.",
        "- docs/archive/ and archives/ are historical; repo_take/ is research-only.",
        "",
        "## Coverage by area",
        "",
        "| Area | Files | Lines |",
        "|---|---:|---:|",
    ]
    for area, rows in sorted(by_area.items()):
        lines.append(
            f"| {area} | {len(rows)} | {sum(row['lines'] for row in rows)} |"
        )
    lines += [
        "",
        "## Complete file manifest",
        "",
        "| Path | Lines | Bytes | SHA-256 prefix |",
        "|---|---:|---:|---|",
    ]
    for row in records:
        lines.append(
            f"| {row['path']} | {row['lines']} | {row['bytes']} | {row['sha256'][:16]} |"
        )
    lines += [
        "",
        "## Review rule",
        "",
        "A file appearing here means only that it is included in the active first-party",
        "Markdown corpus. Use owner contracts for normative meaning, source for actual",
        "implementation, schemas for machine contracts and CODE/SYSTEM/USER evidence",
        "for qualification. Do not use old reading digests or archive documents as",
        "current authority.",
        "",
    ]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"active corpus: files={len(records)} lines={total_lines} "
        f"bytes={total_bytes}"
    )

if __name__ == "__main__":
    emit(collect())
